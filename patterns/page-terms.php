	<h2>1. Definities</h2>
	<p>In deze voorwaarden wordt verstaan onder "XGOUD": de onderneming gevestigd te Eindhoven die edelmetalen, edelstenen en horloges inkoopt. "Klant": iedere natuurlijke of rechtspersoon die producten aanbiedt of een afspraak maakt.</p>

	<h2>2. Toepasselijkheid</h2>
	<p>Deze voorwaarden zijn van toepassing op alle aanbiedingen, taxaties, afspraken en overeenkomsten tussen XGOUD en de klant.</p>

	<h2>3. Taxatie en prijsindicatie</h2>
	<p>Online berekeningen en indicaties zijn vrijblijvend en niet bindend. Voor edelmetalen geldt een vaste dagprijs op basis van de actuele spotkoers; voor edelstenen en horloges geldt een prijsindicatie. De definitieve prijs wordt vastgesteld na fysieke taxatie.</p>

	<h2>4. Totstandkoming van de overeenkomst</h2>
	<p>Een overeenkomst komt tot stand zodra de klant akkoord gaat met het definitieve bod na taxatie. De klant verklaart rechtmatig eigenaar te zijn van de aangeboden zaken.</p>

	<h2>5. Identificatie</h2>
	<p>XGOUD is wettelijk verplicht de identiteit van de klant vast te stellen. De klant dient een geldig legitimatiebewijs te tonen.</p>

	<h2>6. Uitbetaling</h2>
	<p>Uitbetaling vindt plaats per bankoverschrijving of, tot een wettelijk toegestaan bedrag, contant. Uitbetaling geschiedt na akkoord en eventuele controle van de aangeboden zaken.</p>

	<h2>7. Afspraken en annulering</h2>
	<p>Afspraken (bezoek aan huis, op kantoor of ophaalservice) kunnen kosteloos worden gewijzigd of geannuleerd via de link in uw bevestiging, tenzij anders vermeld.</p>

	<h2>8. Goede doelen</h2>
	<p>Van elke transactie gaat een vast deel van de marge naar een goed doel. De klant kan een categorie of concrete instelling kiezen. XGOUD bepaalt de uiteindelijke uitkering en periode.</p>

	<h2>9. Aansprakelijkheid</h2>
	<p>XGOUD is niet aansprakelijk voor indirecte schade. De aansprakelijkheid is in alle gevallen beperkt tot het bedrag van de betreffende transactie.</p>

	<h2>10. Toepasselijk recht</h2>
	<p>Op alle overeenkomsten is Nederlands recht van toepassing. Geschillen worden voorgelegd aan de bevoegde rechter in het arrondissement Oost-Brabant.</p>
