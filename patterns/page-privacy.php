	<p>Wij bewaren uw gegevens niet langer dan noodzakelijk. Fiscale en administratieve gegevens bewaren wij conform de wettelijke bewaarplicht (doorgaans 7 jaar). Identificatiegegevens uit hoofde van de Wwft bewaren wij gedurende de wettelijke termijn (in beginsel 5 jaar na het einde van de transactie/relatie). Overige gegevens verwijderen wij zodra het doel is vervuld.</p>

